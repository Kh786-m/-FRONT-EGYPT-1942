#!/usr/bin/env python3
"""HARAQ procedural sound effects (all synthesised from noise/oscillators by this script).

Output: assets/audio/*.ogg (mono Vorbis). The sounds are original works generated by code,
released as CC0 together with this script. Re-run:  python3 tools/gen_audio.py
Needs numpy + ffmpeg (libvorbis).
"""
import os, subprocess, tempfile, wave
import numpy as np

SR = 32000
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "audio")
rng = np.random.default_rng(1942)


def t_axis(dur):
    return np.arange(int(dur * SR)) / SR


def noise(dur):
    return rng.standard_normal(int(dur * SR))


def band(x, lo=None, hi=None, soft=0.15):
    """Zero-phase FFT band filter with soft (log-domain) edges."""
    n = len(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    X = np.fft.rfft(x)
    m = np.ones_like(f)
    lf = np.log2(np.maximum(f, 1.0))
    if lo:
        m *= 1 / (1 + np.exp(-(lf - np.log2(lo)) / soft))
    if hi:
        m *= 1 / (1 + np.exp((lf - np.log2(hi)) / soft))
    return np.fft.irfft(X * m, n)


def env_exp(dur, tau, attack=0.002):
    t = t_axis(dur)
    e = np.exp(-t / tau)
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return e * a


def norm(x, peak=0.9):
    m = np.max(np.abs(x)) + 1e-9
    return x / m * peak


def soft_clip(x, drive=2.0):
    return np.tanh(x * drive) / np.tanh(drive)


def pad(x, dur):
    n = int(dur * SR)
    out = np.zeros(max(n, len(x)))
    out[: len(x)] = x
    return out


def place(buf, x, at):
    i = int(at * SR)
    j = min(len(buf), i + len(x))
    buf[i:j] += x[: j - i]


def reverb_tail(x, dur=0.6, level=0.25, lo=200, hi=3000):
    """Cheap desert 'slap' + diffuse tail made from filtered decaying noise convolution."""
    ir = noise(dur) * env_exp(dur, dur / 4)
    ir = band(ir, lo, hi)
    ir[: int(0.012 * SR)] = 0
    y = np.convolve(x, ir)[: len(x) + len(ir) - 1]
    return np.concatenate([x, np.zeros(len(ir) - 1)]) + norm(y, np.max(np.abs(x)) * level)


def gunshot(body_hz, crack_hi, crack_tau, boom_tau, tail, dur, mech=0.0):
    d = dur
    crack = band(noise(d), 900, crack_hi) * env_exp(d, crack_tau, 0.0005)
    boom = band(noise(d), 40, body_hz) * env_exp(d, boom_tau, 0.001) * 2.2
    t = t_axis(d)
    thump = np.sin(2 * np.pi * (body_hz * 0.45) * t * (1 - 0.3 * t)) * env_exp(d, boom_tau * 0.8) * 0.9
    x = crack * 1.0 + boom + thump
    if mech > 0:
        clk = band(noise(0.02), 2500, 9000) * env_exp(0.02, 0.003)
        place(x, clk * mech, 0.004)
    x = soft_clip(norm(x), 2.5)
    return norm(reverb_tail(x, tail, 0.35), 0.95)


def click(dur=0.03, lo=2000, hi=9000, tau=0.004):
    return band(noise(dur), lo, hi) * env_exp(dur, tau, 0.0003)


def clunk(freq=900, dur=0.08, tau=0.02):
    t = t_axis(dur)
    tone = np.sin(2 * np.pi * freq * t) * 0.6 + np.sin(2 * np.pi * freq * 2.7 * t) * 0.25
    return (tone + band(noise(dur), 600, 5000) * 0.6) * env_exp(dur, tau, 0.0005)


def write(name, x, quality=3, loop_fade=0.0):
    x = np.asarray(x, dtype=np.float64)
    if loop_fade > 0:
        # Seamless loop: crossfade the tail into the head.
        n = int(loop_fade * SR)
        head, tail = x[:n].copy(), x[-n:].copy()
        w = np.linspace(0, 1, n)
        x = x[:-n].copy()
        x[:n] = head * w + tail * (1 - w)
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    os.makedirs(OUT, exist_ok=True)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as f:
        tmp = f.name
    with wave.open(tmp, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    dst = os.path.join(OUT, name + ".ogg")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-c:a", "libvorbis", "-q:a", str(quality), "-ar", "22050" if loop_fade else str(SR), dst], check=True)
    os.unlink(tmp)
    print(f"{name:16s} {len(x)/SR:5.2f}s {os.path.getsize(dst)/1024:6.1f} KB")


def main():
    # --- Weapons
    write("shot_webley", gunshot(220, 7000, 0.010, 0.05, 0.45, 0.42, mech=0.4))
    write("shot_enfield", gunshot(160, 9000, 0.014, 0.08, 0.9, 0.75))
    write("shot_thompson", gunshot(260, 6500, 0.008, 0.035, 0.3, 0.22, mech=0.6))
    write("shot_mp40", gunshot(300, 7500, 0.007, 0.03, 0.28, 0.2, mech=0.7))
    far = band(gunshot(140, 3500, 0.02, 0.09, 1.0, 0.7), 80, 2600)
    write("shot_enemy", norm(far, 0.85))
    # Dry fire.
    write("dry", norm(click(0.06, 1500, 7000, 0.006) + clunk(1400, 0.06, 0.008) * 0.4, 0.7))
    # Reload: mag out, mag in, bolt/charging handle.
    r = np.zeros(int(1.5 * SR))
    place(r, clunk(700, 0.12, 0.03) * 0.8, 0.05)
    place(r, click(0.05, 1200, 6000, 0.01) * 0.5, 0.12)
    place(r, clunk(520, 0.15, 0.035), 0.75)
    place(r, click(0.04, 2000, 8000, 0.006) * 0.9, 0.79)
    place(r, clunk(1100, 0.1, 0.02) * 0.9, 1.18)
    place(r, click(0.05, 2500, 9000, 0.008), 1.27)
    write("reload", norm(r, 0.8))
    # Weapon draw / switch.
    s = np.zeros(int(0.4 * SR))
    place(s, band(noise(0.25), 800, 5000) * env_exp(0.25, 0.06, 0.05) * 0.4, 0.0)
    place(s, clunk(950, 0.1, 0.02), 0.2)
    write("switch", norm(s, 0.6))
    # --- Hits
    d = 0.25
    t = t_axis(d)
    flesh = band(noise(d), 80, 900) * env_exp(d, 0.03, 0.001) + np.sin(2 * np.pi * 95 * t) * env_exp(d, 0.04) * 0.8
    write("hit_flesh", norm(soft_clip(norm(flesh), 2.0), 0.85))
    d = 0.35
    sand = band(noise(d), 300, 5000) * env_exp(d, 0.05, 0.001) + band(noise(d), 2000, 9000) * env_exp(d, 0.12, 0.01) * 0.25
    write("hit_sand", norm(sand, 0.6))
    d = 0.9
    t = t_axis(d)
    f0 = 2600 * np.exp(-t * 0.9)
    ping = np.sin(2 * np.pi * np.cumsum(f0) / SR) * env_exp(d, 0.18, 0.002) * 0.5
    ping += np.sin(2 * np.pi * 4100 * t) * env_exp(d, 0.05) * 0.3 + click(d, 3000, 12000, 0.004)
    write("hit_metal", norm(ping, 0.7))
    d = 0.4
    t = t_axis(d)
    hurt = np.sin(2 * np.pi * 70 * t) * env_exp(d, 0.08, 0.002) + band(noise(d), 60, 600) * env_exp(d, 0.05) * 0.8
    write("hurt", norm(soft_clip(norm(hurt), 2.5), 0.9))
    # --- Explosion (distant artillery shell)
    d = 3.2
    t = t_axis(d)
    boom = band(noise(d), 25, 420) * env_exp(d, 0.55, 0.01) * 2.0
    boom += np.sin(2 * np.pi * 42 * t * (1 - 0.15 * t)) * env_exp(d, 0.5, 0.005) * 1.4
    debris = band(noise(d), 600, 4000) * env_exp(d, 0.9, 0.3) * 0.12
    write("explosion", norm(soft_clip(norm(boom + debris), 3.0), 0.95))
    # Zone burn loop: crackle + hiss, while the player is outside the circle.
    d = 4.0
    crack = np.zeros(int(d * SR))
    for k in range(70):
        place(crack, click(0.02, 1500, 9000, 0.003) * rng.uniform(0.2, 1.0), rng.uniform(0, d - 0.03))
    hiss = band(noise(d), 400, 3000) * 0.18 * (1 + 0.4 * np.sin(2 * np.pi * 0.5 * t_axis(d)))
    rumble = band(noise(d), 30, 160) * 0.5
    write("zone_burn", norm(crack + hiss + rumble, 0.7), loop_fade=0.4)
    # Zone alarm: brass horn two-tone.
    d = 1.6
    t = t_axis(d)
    f = np.where(t < 0.8, 440, 330)
    ph = np.cumsum(2 * np.pi * f / SR)
    horn = sum(np.sin(ph * k) / k for k in range(1, 7)) * np.minimum(1, np.minimum(t, d - t) * 20)
    write("zone_alarm", norm(band(horn, 150, 3500), 0.6))
    # --- Footsteps on sand (3 variants packed into one stream via random pitch is fine; keep one).
    d = 0.22
    step = band(noise(d), 150, 2500) * env_exp(d, 0.035, 0.008) + band(noise(d), 2000, 7000) * env_exp(d, 0.06, 0.02) * 0.25
    write("step", norm(step, 0.55))
    # --- Ambience loops (22.05 kHz)
    d = 12.4
    n = int(d * SR)
    w = band(noise(d), 120, 900)
    gust = 0.55 + 0.45 * np.sin(2 * np.pi * t_axis(d) / 6.2) * np.sin(2 * np.pi * t_axis(d) / 3.1 + 1)
    whistle = band(noise(d), 1200, 2200, 0.05) * (0.15 + 0.1 * np.sin(2 * np.pi * t_axis(d) / 12.4)) * 0.6
    write("wind_loop", norm(w * gust + whistle, 0.55), quality=2, loop_fade=0.4)
    d = 12.4
    t = t_axis(d)
    surf = band(noise(d), 60, 1800)
    swell = np.clip(np.sin(2 * np.pi * t / 6.2) * 0.5 + 0.5, 0, 1) ** 2
    wash = band(noise(d), 1500, 6000) * np.clip(np.sin(2 * np.pi * t / 6.2 - 0.6), 0, 1) ** 3 * 0.4
    write("sea_loop", norm(surf * (0.25 + 0.75 * swell) + wash, 0.6), quality=2, loop_fade=0.4)
    # --- UI
    d = 0.08
    t = t_axis(d)
    ui = np.sin(2 * np.pi * 1700 * t) * env_exp(d, 0.012, 0.0005) * 0.6 + click(d, 3000, 9000, 0.003) * 0.4
    write("ui_click", norm(ui, 0.6))
    # Loot pickup (metal clink + cloth).
    d = 0.45
    t = t_axis(d)
    pk = (np.sin(2 * np.pi * 1320 * t) + 0.5 * np.sin(2 * np.pi * 1980 * t)) * env_exp(d, 0.09, 0.001) * 0.4
    pk += band(noise(d), 500, 3000) * env_exp(d, 0.05, 0.02) * 0.4
    write("pickup", norm(pk, 0.6))


if __name__ == "__main__":
    main()
