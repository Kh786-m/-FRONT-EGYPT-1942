# ---------------------------------------------------------------------------- music
# Two short loops, composed note by note in code: a North African / WW2 desert-war feel —
# Hijaz (Phrygian dominant) melody on a plucked oud-like string, frame drum (bendir/darbuka),
# military side drum, and a low brass drone / horn calls.
MSR = 22050
HIJAZ = [0, 1, 4, 5, 7, 8, 10]  # D Eb F# G A Bb C


def m_t(dur):
    return np.arange(int(dur * MSR)) / MSR


def m_noise(dur):
    return rng.standard_normal(int(dur * MSR))


def m_band(x, lo=None, hi=None, soft=0.15):
    n = len(x)
    f = np.fft.rfftfreq(n, 1 / MSR)
    X = np.fft.rfft(x)
    m = np.ones_like(f)
    lf = np.log2(np.maximum(f, 1.0))
    if lo:
        m *= 1 / (1 + np.exp(-(lf - np.log2(lo)) / soft))
    if hi:
        m *= 1 / (1 + np.exp((lf - np.log2(hi)) / soft))
    return np.fft.irfft(X * m, n)


def m_place(buf, x, at):
    i = int(at * MSR) % len(buf)
    j = min(len(buf), i + len(x))
    buf[i:j] += x[: j - i]
    rest = len(x) - (j - i)
    if rest > 0:  # wrap around: the loop stays seamless
        buf[:rest] += x[j - i:]


def hz(semi, base=146.83):  # D3
    return base * 2 ** (semi / 12)


def scale(deg, octave=0):
    o, k = divmod(deg, 7)
    return HIJAZ[k] + 12 * (o + octave)


def pluck(f, dur=1.2, bright=0.5, decay=0.996):
    """Karplus-Strong string (oud-like): vectorised one period at a time."""
    n = int(dur * MSR)
    p = max(2, int(MSR / f))
    buf = m_band(m_noise(p * 4), 80, 1500 + bright * 4000)[:p]
    out = np.zeros(n + p)
    out[:p] = buf
    for i in range(p, n + p, p):
        prev = out[i - p:i]
        nxt = 0.5 * (prev + np.roll(prev, 1)) * decay
        k = min(p, n + p - i)
        out[i:i + k] = nxt[:k]
    y = out[:n]
    y *= np.minimum(1, np.arange(n) / 40)
    body = m_band(y, 150, 2500) * 0.6 + y * 0.4
    return body


def horn(f, dur, vib=5.0, bright=6):
    t = m_t(dur)
    ph = 2 * np.pi * np.cumsum(f * (1 + 0.004 * np.sin(2 * np.pi * vib * t))) / MSR
    x = sum(np.sin(ph * k) * (1 / k ** 1.2) for k in range(1, bright + 1))
    env = np.minimum(1, t / 0.08) * np.minimum(1, (dur - t) / 0.25)
    return m_band(x * env, 90, 2600)


def drone(f, dur):
    t = m_t(dur)
    x = sum(np.sin(2 * np.pi * f * k * t + k) * (0.6 / k) for k in (1, 2, 3, 4))
    return x * (0.75 + 0.25 * np.sin(2 * np.pi * t / dur))


def frame_drum(kind="dum", amp=1.0):
    d = 0.5 if kind == "dum" else 0.18
    t = m_t(d)
    if kind == "dum":
        f = 70 * np.exp(-t * 8) + 58
        x = np.sin(2 * np.pi * np.cumsum(f) / MSR) * np.exp(-t / 0.16) + m_band(m_noise(d), 60, 500) * np.exp(-t / 0.03) * 0.5
    else:  # "tek" rim
        x = m_band(m_noise(d), 1500, 7000) * np.exp(-t / 0.025) + np.sin(2 * np.pi * 420 * t) * np.exp(-t / 0.03) * 0.4
    return x * amp


def snare(amp=1.0, d=0.22):
    t = m_t(d)
    x = m_band(m_noise(d), 900, 7000) * np.exp(-t / 0.05) + np.sin(2 * np.pi * 190 * t) * np.exp(-t / 0.03) * 0.6
    return x * amp


def bass_drum(amp=1.0):
    d = 0.6
    t = m_t(d)
    f = 90 * np.exp(-t * 14) + 45
    return np.sin(2 * np.pi * np.cumsum(f) / MSR) * np.exp(-t / 0.22) * amp


def m_reverb(x, tail=2.0, level=0.25):
    ir = m_noise(tail) * np.exp(-m_t(tail) / (tail / 5))
    ir = m_band(ir, 200, 3500)
    ir[: int(0.04 * MSR)] = 0
    wet = np.fft.irfft(np.fft.rfft(x, len(x) + len(ir)) * np.fft.rfft(ir, len(x) + len(ir)))
    wet = wet[: len(x)] + np.concatenate([wet[len(x):], np.zeros(len(x))])[: len(x)]  # wrap tail
    return x + norm(wet, np.max(np.abs(x)) * level)


def write_music(name, x, quality=1):
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as f:
        tmp = f.name
    with wave.open(tmp, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(MSR)
        w.writeframes(pcm.tobytes())
    dst = os.path.join(OUT, name + ".ogg")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-c:a", "libvorbis", "-q:a", str(quality), dst], check=True)
    os.unlink(tmp)
    print(f"{name:16s} {len(x)/MSR:5.2f}s {os.path.getsize(dst)/1024:6.1f} KB")


def menu_theme():
    """Slow, wistful: oud taqsim-like phrase over a D drone, distant horn call, sparse bendir."""
    bpm = 72
    beat = 60 / bpm
    bars = 12
    dur = bars * 4 * beat
    x = np.zeros(int(dur * MSR))
    x += m_band(drone(hz(-12), dur), 40, 900) * 0.22
    x += m_band(drone(hz(-5), dur), 40, 900) * 0.08
    phrase = [(0, 1), (1, 0.5), (2, 0.5), (3, 1), (2, 0.5), (1, 0.5), (0, 2), (4, 1), (5, 0.5), (4, 0.5),
              (3, 1), (2, 1), (1, 2), (2, 1), (3, 0.5), (4, 0.5), (5, 1), (6, 1), (7, 2), (6, 0.5), (5, 0.5),
              (4, 1), (3, 1), (2, 0.5), (1, 0.5), (0, 3), (-1, 1), (0, 4)]
    t = 0.0
    for rep in range(2):
        t = rep * 6 * 4 * beat
        for deg, length in phrase:
            if t >= dur:
                break
            n = pluck(hz(scale(deg, 1)), min(2.4, length * beat + 0.8), 0.55, 0.9965)
            m_place(x, n * 0.5, t)
            # Tremolo double-strikes on long notes, oud style.
            if length >= 2:
                for k in range(1, int(length * 2)):
                    m_place(x, pluck(hz(scale(deg, 1)), 0.5, 0.4, 0.993) * 0.18, t + k * beat * 0.5)
            t += length * beat
    for bar in range(bars):
        b0 = bar * 4 * beat
        m_place(x, frame_drum("dum", 0.5), b0)
        m_place(x, frame_drum("tek", 0.18), b0 + 1.5 * beat)
        m_place(x, frame_drum("dum", 0.3), b0 + 2.5 * beat)
        m_place(x, frame_drum("tek", 0.15), b0 + 3 * beat)
    # Distant bugle/horn call in bars 5 and 11.
    for b in (4, 10):
        b0 = b * 4 * beat
        for k, (deg, ln) in enumerate([(0, 1), (4, 1), (7, 2)]):
            m_place(x, horn(hz(scale(deg, 0)), ln * beat * 0.95) * 0.16, b0 + sum(l for _, l in [(0, 1), (4, 1), (7, 2)][:k]) * beat)
    return norm(m_reverb(x, 2.4, 0.35), 0.7)


def battle_theme():
    """Tense in-match loop: 112 bpm military side drum + darbuka maqsum, low Hijaz ostinato,
    brass stabs and a rising horn line. Kept under the SFX in the mix."""
    bpm = 112
    beat = 60 / bpm
    bars = 16
    dur = bars * 4 * beat
    x = np.zeros(int(dur * MSR))
    x += m_band(drone(hz(-12), dur), 40, 500) * 0.16
    ost = [0, 1, 0, 4, 3, 1, 0, 1]
    for bar in range(bars):
        b0 = bar * 4 * beat
        # Maqsum: DUM tek - tek DUM - tek -
        for at, k, a in [(0, "dum", 0.7), (1, "tek", 0.3), (1.5, "tek", 0.25), (2, "dum", 0.55), (3, "tek", 0.3)]:
            m_place(x, frame_drum(k, a), b0 + at * beat)
        m_place(x, bass_drum(0.6), b0)
        m_place(x, bass_drum(0.4), b0 + 2 * beat)
        # Side-drum ruffs, a march roll every 4th bar.
        for s16 in range(16):
            if bar % 4 == 3 and s16 >= 8:
                m_place(x, snare(0.12 + 0.02 * (s16 - 8)), b0 + s16 * beat / 4)
                m_place(x, snare(0.08), b0 + s16 * beat / 4 + beat / 8)
            elif s16 in (4, 12):
                m_place(x, snare(0.25), b0 + s16 * beat / 4)
            elif s16 in (3, 11, 15):
                m_place(x, snare(0.08, 0.1), b0 + s16 * beat / 4)
        # Low plucked ostinato (8ths).
        shift = 0 if bar % 8 < 4 else (3 if bar % 8 < 6 else 4)
        for i, deg in enumerate(ost):
            m_place(x, pluck(hz(scale(deg + shift, -1)), 0.5, 0.35, 0.992) * 0.45, b0 + i * beat / 2)
        # Brass stabs on bar starts in the second half.
        if bar >= 8 and bar % 2 == 0:
            for semi in (0, 7, 12):
                m_place(x, horn(hz(scale(shift, -1) + semi), beat * 0.6, 0, 5) * 0.09, b0)
    # A rising horn line over bars 9-16.
    line = [(0, 2), (1, 2), (2, 4), (3, 2), (4, 2), (5, 4), (4, 2), (5, 2), (6, 2), (7, 2), (8, 6), (7, 2)]
    t = 8 * 4 * beat
    for deg, ln in line:
        if t >= dur:
            break
        m_place(x, horn(hz(scale(deg, 0)), ln * beat * 0.92) * 0.12, t)
        t += ln * beat
    return norm(m_reverb(x, 1.6, 0.22), 0.7)


