#!/usr/bin/env python3
"""HARAQ procedural sound effects (all synthesised from noise/oscillators by this script).

Output: assets/audio/*.ogg (mono Vorbis). The sounds are original works generated by code,
released as CC0 together with this script. Re-run:  python3 tools/gen_audio.py
Needs numpy + ffmpeg (libvorbis).
"""
import os, subprocess, tempfile, wave
import numpy as np

SR = 32000
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "audio")
rng = np.random.default_rng(1942)


def t_axis(dur):
    return np.arange(int(dur * SR)) / SR


def noise(dur):
    return rng.standard_normal(int(dur * SR))


def band(x, lo=None, hi=None, soft=0.15):
    """Zero-phase FFT band filter with soft (log-domain) edges."""
    n = len(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    X = np.fft.rfft(x)
    m = np.ones_like(f)
    lf = np.log2(np.maximum(f, 1.0))
    if lo:
        m *= 1 / (1 + np.exp(-(lf - np.log2(lo)) / soft))
    if hi:
        m *= 1 / (1 + np.exp((lf - np.log2(hi)) / soft))
    return np.fft.irfft(X * m, n)


def env_exp(dur, tau, attack=0.002):
    t = t_axis(dur)
    e = np.exp(-t / tau)
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return e * a


def norm(x, peak=0.9):
    m = np.max(np.abs(x)) + 1e-9
    return x / m * peak


def soft_clip(x, drive=2.0):
    return np.tanh(x * drive) / np.tanh(drive)


def pad(x, dur):
    n = int(dur * SR)
    out = np.zeros(max(n, len(x)))
    out[: len(x)] = x
    return out


def place(buf, x, at):
    i = int(at * SR)
    j = min(len(buf), i + len(x))
    buf[i:j] += x[: j - i]


def reverb_tail(x, dur=0.6, level=0.25, lo=200, hi=3000):
    """Cheap desert 'slap' + diffuse tail made from filtered decaying noise convolution."""
    ir = noise(dur) * env_exp(dur, dur / 4)
    ir = band(ir, lo, hi)
    ir[: int(0.012 * SR)] = 0
    y = np.convolve(x, ir)[: len(x) + len(ir) - 1]
    return np.concatenate([x, np.zeros(len(ir) - 1)]) + norm(y, np.max(np.abs(x)) * level)


def desert_reverb(x, tail=1.2, level=0.3, lo=150, hi=2800, taps=((0.045, 0.45), (0.11, 0.3), (0.23, 0.18), (0.41, 0.1))):
    """Open-desert space: a few discrete slaps off dunes / ruins, then a long, darkening tail."""
    n_out = len(x) + int((tail + 0.5) * SR)
    y = np.zeros(n_out)
    y[: len(x)] += x
    dark = band(x, lo, hi)
    for delay, g in taps:
        place(y, dark * g * level * 2.0, delay)
    d = tail
    ir = noise(d) * env_exp(d, d / 5.0, 0.02)
    # Higher frequencies die faster in the tail (air absorption).
    ir = band(ir, lo, hi) * 0.7 + band(ir, lo, hi * 0.35) * 0.6
    ir[: int(0.03 * SR)] = 0
    m = len(x) + len(ir) - 1
    wet = np.fft.irfft(np.fft.rfft(x, m) * np.fft.rfft(ir, m), m)
    wet = norm(wet, np.max(np.abs(x)) * level)
    y[: len(wet)] += wet[: n_out]
    return y


def gunshot(body_hz, crack_hi, crack_tau, boom_tau, tail, dur, mech=0.0, level=0.35, sub=1.0):
    """Layered shot: supersonic crack + muzzle blast body + low sub thump + action mechanics,
    then the desert reverb tail."""
    d = dur
    t = t_axis(d)
    crack = band(noise(d), 1800, crack_hi) * env_exp(d, crack_tau * 0.6, 0.0002) * 1.1
    snap = band(noise(d), 700, 4000) * env_exp(d, crack_tau, 0.0004) * 0.8
    blast = band(noise(d), 60, body_hz * 2.2) * env_exp(d, boom_tau, 0.0008) * 2.0
    f = body_hz * 0.42 * np.exp(-t * 6.0) + body_hz * 0.18
    thump = np.sin(2 * np.pi * np.cumsum(f) / SR) * env_exp(d, boom_tau * 1.3, 0.001) * 1.1 * sub
    x = crack + snap + blast + thump
    if mech > 0:
        place(x, band(noise(0.02), 2500, 9000) * env_exp(0.02, 0.003) * mech, 0.003)
        place(x, clunk(1500, 0.05, 0.01) * mech * 0.5, min(d - 0.06, 0.06))
    x = soft_clip(norm(x), 3.0)
    return norm(desert_reverb(x, tail, level), 0.95)


def click(dur=0.03, lo=2000, hi=9000, tau=0.004):
    return band(noise(dur), lo, hi) * env_exp(dur, tau, 0.0003)


def clunk(freq=900, dur=0.08, tau=0.02):
    t = t_axis(dur)
    tone = np.sin(2 * np.pi * freq * t) * 0.6 + np.sin(2 * np.pi * freq * 2.7 * t) * 0.25
    return (tone + band(noise(dur), 600, 5000) * 0.6) * env_exp(dur, tau, 0.0005)


def write(name, x, quality=3, loop_fade=0.0):
    x = np.asarray(x, dtype=np.float64)
    if loop_fade > 0:
        # Seamless loop: crossfade the tail into the head.
        n = int(loop_fade * SR)
        head, tail = x[:n].copy(), x[-n:].copy()
        w = np.linspace(0, 1, n)
        x = x[:-n].copy()
        x[:n] = head * w + tail * (1 - w)
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    os.makedirs(OUT, exist_ok=True)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as f:
        tmp = f.name
    with wave.open(tmp, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    dst = os.path.join(OUT, name + ".ogg")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp, "-c:a", "libvorbis", "-q:a", str(quality), "-ar", "22050" if loop_fade else str(SR), dst], check=True)
    os.unlink(tmp)
    print(f"{name:16s} {len(x)/SR:5.2f}s {os.path.getsize(dst)/1024:6.1f} KB")


